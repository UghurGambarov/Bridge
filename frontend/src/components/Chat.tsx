const PROMPTS: Record<string, string[]> = {
  [PERSONA.mother]: ["这个可以付吗？", "Send Li Wei an extra £2,000 now.", "用我哥哥的额度付吧", "我还剩多少额度？", "Why?"],
  [PERSONA.student]: ["What is waiting for my confirmation?", "Why?"],
};

export function Composer() {
  const { send, upload, busy, persona, ready } = useStore();
  const [text, setText] = useState("");
  const [samples, setSamples] = useState<string[]>([]);
  const file = useRef<HTMLInputElement>(null);
  useEffect(() => {
    api.samples().then((r) => setSamples(r.samples)).catch(() => setSamples([]));
  }, []);
  const submit = async () => {
    const t = text.trim();
    if (!t || busy) return;
    setText("");
    await send(t);
  };
  const doUpload = async (f: File) => {
    const t = text;
    setText("");
    await upload(f, t);
  };
  return (
    <div className="border-t border-rule bg-paper-raised/80 px-5 pb-4 pt-3 backdrop-blur">
      <div className="mb-2 flex flex-wrap gap-1.5">
        {(PROMPTS[persona] ?? []).map((p) => (
          <button key={p} className="chip-neutral hover:border-ink" onClick={() => setText(p)}>{p}</button>
        ))}
      </div>
      <div className="flex items-end gap-2">
        <label className="btn-ghost h-[46px] cursor-pointer" title="Upload an invoice, letter or message (PDF, TXT, EML)">
          📎 Upload
          <input data-testid="upload-input" ref={file} type="file" accept=".pdf,.txt,.eml" className="hidden"
            onChange={(e) => { const f = e.target.files?.[0]; if (f) doUpload(f); e.target.value = ""; }} />
        </label>
        <select data-testid="sample-select" className="btn-ghost h-[46px] max-w-[180px] bg-transparent" value=""
          title="Upload one of the fictional SANDBOX sample documents"
          onChange={async (e) => { const n = e.target.value; if (n) await doUpload(await api.sampleFile(n)); }}>
          <option value="">Sample docs…</option>
          {samples.map((s) => <option key={s} value={s}>{s}</option>)}
        </select>
        <textarea data-testid="chat-input" rows={1} value={text} disabled={!ready}
          placeholder={persona === PERSONA.mother ? "Write to Bridge… 用中文或英文都可以" : "Write to Bridge…"}
          onChange={(e) => setText(e.target.value)}
          onKeyDown={(e) => { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); submit(); } }}
          className="h-[46px] min-h-[46px] flex-1 resize-none rounded-md border border-rule-strong bg-paper px-3.5 py-3 text-[15px] outline-none focus:border-ink" />
        <button data-testid="chat-send" className="btn-primary h-[46px] px-5" disabled={busy || !text.trim()} onClick={submit}>Send</button>
      </div>
      <div className="mt-1.5 text-[11.5px] text-ink-mute">
        Typing first, then uploading, sends your text with the document. Bridge never sees raw document text — only checked fields.
      </div>
    </div>
  );
}
