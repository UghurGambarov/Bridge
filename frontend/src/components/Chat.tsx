import { useEffect, useRef, useState } from "react";
import { CardView } from "../cards/Cards";
import { api } from "../lib/api";
import { personaName, PERSONA } from "../lib/format";
import { useStore } from "../lib/store";

function AiBadge() {
  return (
    <span className="rounded border border-rule-strong px-1.5 py-[1px] text-[10.5px] font-medium tracking-wide text-ink-mute" title="AI-001: AI-generated content is labelled">
      AI-generated · AI生成
    </span>
  );
}

export function Thread() {
  const { turns } = useStore();
  const end = useRef<HTMLDivElement>(null);
  useEffect(() => {
    end.current?.scrollIntoView({ behavior: "smooth", block: "end" });
  }, [turns]);
  if (!turns.length) return <Welcome />;
  return (
    <div className="space-y-6 pb-4">
      {turns.map((t) => (
        <div key={t.key} className="space-y-3">
          {t.user?.text && (
            <div className="flex justify-end rise">
              <div className="max-w-[78%] rounded-lg rounded-br-sm bg-ink px-4 py-2.5 text-paper">
                <div className="mb-0.5 text-[11px] uppercase tracking-[0.12em] text-paper/60">{personaName(t.user.persona)}</div>
                <div className="whitespace-pre-wrap text-[14.5px] leading-relaxed">{t.user.text}</div>
                {t.user.doc_ids?.length > 0 && <div className="mt-1 text-[11.5px] text-paper/70">📎 document attached ({t.user.doc_ids.join(", ")})</div>}
              </div>
            </div>
          )}
          {t.pending && (
            <div className="flex items-center gap-2 text-ink-mute rise">
              <Avatar />
              <span className="typing text-[20px] leading-none"><span>·</span><span>·</span><span>·</span></span>
              <span className="text-[12.5px]">checking with the policy engine…</span>
            </div>
          )}
          {t.error && <div className="text-[13px] text-block">⚠ {t.error}</div>}
          {t.messages.map((m, i) => (
            <div key={i} className="flex items-start gap-2.5 rise">
              <Avatar system={!m.ai_generated} />
              <div className="max-w-[86%]">
                <div className="mb-1 flex items-center gap-2">
                  <span className="text-[12px] font-medium">{m.ai_generated ? "Bridge agent" : "Bridge system"}</span>
                  {m.ai_generated ? <AiBadge /> : <span className="text-[10.5px] text-ink-mute">generated by code</span>}
                </div>
                <div lang={/[一-鿿]/.test(m.text) ? "zh-CN" : "en"} className="whitespace-pre-wrap text-[15px] leading-relaxed">{m.text}</div>
              </div>
            </div>
          ))}
          {t.cards.length > 0 && (
            <div className="space-y-3 pl-10">
              {t.cards.map((c, i) => <CardView key={i} card={c} delay={i * 90} />)}
            </div>
          )}
        </div>
      ))}
      <div ref={end} />
    </div>
  );
}

function Avatar({ system }: { system?: boolean }) {
  return (
    <span className={`mt-0.5 inline-flex h-7 w-7 shrink-0 items-center justify-center rounded-full border font-display text-[14px] ${system ? "border-rule-strong text-ink-mute" : "border-ink bg-ink text-paper"}`}>
      B
    </span>
  );
}

