"""Provider-neutral LLM interface.

Messages use one internal format (OpenAI-like):
  {"role": "system"|"user"|"assistant"|"tool", "content": str,
   "tool_calls": [{"id", "name", "arguments": dict}],   # assistant only
   "tool_call_id": str, "name": str}                    # tool only
Each provider converts to and from its own wire format.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Optional


@dataclass
class ToolCall:
    id: str
    name: str
    arguments: Any  # usually a dict; may be malformed from a compromised model


@dataclass
class LLMResponse:
    text: str = ""
    tool_calls: list[ToolCall] = field(default_factory=list)
    raw: Optional[dict] = None


class LLMError(Exception):
    pass


class LLMProvider:
    provider = "base"
    model = ""

    @property
    def label(self) -> str:
        return f"{self.provider} · {self.model}"

    def chat(self, messages: list[dict], tools: list[dict]) -> LLMResponse:
        """Planner call. `tools` are JSON-schema tool definitions."""
        raise NotImplementedError

    def extract_json(self, system: str, text: str) -> dict:
        """Quarantined extractor call: no tools, JSON object only."""
        raise NotImplementedError

    def explain(self, system: str, prompt: str) -> str:
        """Short plain-language explanation (labelled AI-generated by the caller)."""
        return ""

    @property
    def is_mock(self) -> bool:
        return self.provider in ("mock", "scripted")
